// Kartenillustrationen als Vektorgrafik (Code) – eigene Zeichnungen statt Emojis.
//
//   node scripts/card-art.mjs                 # schreibt public/assets/cards/<name>.svg + .webp
//   node scripts/card-art.mjs --sheet out.png # zusätzlich Übersichtsbild aller Karten
//
// SVG nutzt die CSS-Karte (scharf in jeder Größe), das WebP (512 px) die 3D-Textur:
// Ein Rasterbild lässt sich überall gefahrlos auf eine Canvas und in WebGL zeichnen.
//
// Stil: niedliche Sammelkarten-Wesen, dicke dunkle Kontur, weich schattierte
// Flächen (radialer Verlauf je Farbe), große glänzende Augen, je Element ein Akzent
// (Flammen, Wasser, Blätter, Blitze). Zeichenfläche 256 × 256, Boden bei y ≈ 228.
// Emojis sahen je Gerät anders aus und ließen sich auf iOS nicht zuverlässig auf
// eine Canvas-Textur zeichnen (nur die Silhouette erschien).

