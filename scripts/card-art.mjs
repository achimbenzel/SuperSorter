const INK = '#2f1d12';
const SW = 5;

// ---------------------------------------------------------------- Farben + Verläufe

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgb2hex = (c) => '#' + c.map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('');
const mix = (a, b, t) => rgb2hex(hex2rgb(a).map((v, i) => v + (hex2rgb(b)[i] - v) * t));

let defs;
/** Weich schattierte Füllung: hell oben links, dunkler zum Rand (Volumen). */
function sh(hex) {
  const id = 's' + hex.slice(1);
  if (!defs.has(id)) {
    defs.set(
      id,
      `<radialGradient id="${id}" cx=".36" cy=".3" r=".9"><stop offset="0" stop-color="${mix(hex, '#ffffff', 0.38)}"/><stop offset=".5" stop-color="${hex}"/><stop offset="1" stop-color="${mix(hex, '#000000', 0.24)}"/></radialGradient>`,
    );
  }
  return `url(#${id})`;
}

// ---------------------------------------------------------------- Bausteine

const stroke = (w = SW) => `stroke="${INK}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"`;
const P = (d, fill, w = SW) => `<path d="${d}" fill="${fill}" ${stroke(w)}/>`;
const PN = (d, fill, extra = '') => `<path d="${d}" fill="${fill}" ${extra}/>`;
const E = (cx, cy, rx, ry, fill, w = SW) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" ${stroke(w)}/>`;
const EN = (cx, cy, rx, ry, fill, extra = '') => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" ${extra}/>`;
const L = (d, w = 3.5, color = INK) => `<path d="${d}" fill="none" stroke="${color}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
const G = (t, ...c) => `<g transform="${t}">${c.join('')}</g>`;
/** Inhalt plus Spiegelbild an der Mittelachse x = cx. */
const sym = (c, cx = 128) => c + G(`translate(${2 * cx},0) scale(-1,1)`, c);

/** Großes glänzendes Auge. look: Blickrichtung in Einheiten. */
function eye(x, y, s = 1, look = [0, 0]) {
  const [lx, ly] = look;
  return (
    EN(x, y, 8 * s, 10 * s, INK) +
    EN(x + lx - 2.6 * s, y + ly - 3.8 * s, 3.4 * s, 3.6 * s, '#fff') +
    EN(x + lx + 2.6 * s, y + ly + 3.4 * s, 1.5 * s, 1.5 * s, '#fff')
  );
}
/** Geschlossenes, fröhliches Auge (^). */
const happyEye = (x, y, s = 1) => L(`M${x - 7 * s},${y + 3 * s} Q${x},${y - 7 * s} ${x + 7 * s},${y + 3 * s}`, 4.2 * s);
const blush = (x, y, s = 1) => EN(x, y, 8 * s, 4.6 * s, '#ff6f86', 'opacity=".5"');
const smile = (x, y, w = 7) => L(`M${x - w},${y} Q${x},${y + w * 0.9} ${x + w},${y}`, 3.6);
/** Katzenmund "w" unter der Nase. */
const catMouth = (x, y, w = 6) => L(`M${x - 2 * w},${y} Q${x - w},${y + w} ${x},${y} Q${x + w},${y + w} ${x + 2 * w},${y}`, 3.4);
const shadow = (cx = 128, rx = 72, cy = 230) => EN(cx, cy, rx, 9, '#000', 'opacity=".16"');

/** Flamme (Spitze nach oben), Größe s, Mittelpunkt unten bei (x,y). */
function flame(x, y, s = 1, rot = 0, colors = ['#ff4d1f', '#ffa41c', '#fff0a0']) {
  const outer = 'M0,0 C-20,0 -28,-20 -20,-38 C-14,-50 -6,-54 -4,-72 C8,-60 26,-46 24,-24 C23,-10 16,0 0,0 Z';
  const mid = 'M0,-4 C-12,-4 -17,-18 -12,-30 C-8,-38 -2,-40 0,-52 C8,-42 16,-32 15,-20 C14,-10 10,-4 0,-4 Z';
  const core = 'M0,-6 C-6,-6 -9,-14 -6,-21 C-3,-26 0,-28 1,-34 C6,-28 9,-21 8,-15 C7,-9 5,-6 0,-6 Z';
  return G(`translate(${x},${y}) rotate(${rot}) scale(${s})`, P(outer, sh(colors[0]), SW / s), PN(mid, colors[1]), PN(core, colors[2]));
}

/** Blatt mit Mittelrippe; Stiel bei (x,y), zeigt nach rechts (rot dreht). */
function leaf(x, y, s = 1, rot = 0, color = '#5cc65a') {
  return G(
    `translate(${x},${y}) rotate(${rot}) scale(${s})`,
    P('M0,0 C10,-18 34,-22 50,-8 C38,8 14,12 0,0 Z', sh(color), SW / s),
    L('M3,-1 C16,-6 30,-8 44,-8', 2.6 / s, mix(color, '#000000', 0.35)),
  );
}

/** Blitz, Mitte bei (x,y). */
function bolt(x, y, s = 1, rot = 0, color = '#ffd21f') {
  // Kleine Blitze mit dünnerer Kontur, sonst bleibt von der Füllung nichts übrig
  const w = s < 0.6 ? 2.4 + s * 2 : SW;
  return G(`translate(${x},${y}) rotate(${rot}) scale(${s})`, P('M6,-32 L-14,4 L-1,4 L-7,32 L15,-7 L2,-7 Z', sh(color), w / s));
}

const bubble = (x, y, r) =>
  `<circle cx="${x}" cy="${y}" r="${r}" fill="#ffffff" fill-opacity=".28" stroke="#ffffff" stroke-width="${Math.max(2, r / 4)}"/>` +
  EN(x - r * 0.35, y - r * 0.35, r * 0.25, r * 0.2, '#fff');

/** Wassertropfen, Mitte bei (x,y). */
const drop = (x, y, s = 1, color = '#7cc8ff') =>
  G(`translate(${x},${y}) scale(${s})`, P('M0,-16 C6,-6 11,1 11,6 C11,13 6,17 0,17 C-6,17 -11,13 -11,6 C-11,1 -6,-6 0,-16 Z', sh(color), 3.5 / s), EN(-4, 4, 2.6, 3.6, '#fff', 'opacity=".8"'));

/** Röhre (Tentakel, Arm): Kontur + Füllung als zwei Linien. */
const tube = (d, w, color) => L(d, w + 7, INK) + L(d, w, color);

/** Inhalt auf eine Ellipse beschneiden (z. B. Streifen auf einem Körper). */
let clipN = 0;
function clipEllipse(cx, cy, rx, ry, content) {
  const id = `c${clipN++}`;
  defs.set(id, `<clipPath id="${id}"><ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}"/></clipPath>`);
  return `<g clip-path="url(#${id})">${content}</g>`;
}

/** Vierzackiger Glitzerstern. */
const sparkle = (x, y, s = 1, color = '#ffffff') =>
  G(`translate(${x},${y}) scale(${s})`, PN('M0,-12 Q2,-2 12,0 Q2,2 0,12 Q-2,2 -12,0 Q-2,-2 0,-12 Z', color));

