const CREATURES = { ...FIRE, ...WATER, ...LEAF, ...BOLT };

// ---------------------------------------------------------------- Ausgabe

function inner(name) {
  defs = new Map();
  const body = CREATURES[name]();
  return `<defs>${[...defs.values()].join('')}</defs>${body}`;
}

export function renderCreature(name) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">${inner(name)}</svg>`;
}

export const CREATURE_NAMES = Object.keys(CREATURES);

async function main() {
  const { default: sharp } = await import('sharp');
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const name of CREATURE_NAMES) {
    const svg = renderCreature(name);
    fs.writeFileSync(path.join(OUT_DIR, `${name}.svg`), svg);
    await sharp(Buffer.from(svg), { density: 144 }).resize(512, 512).webp({ quality: 86, alphaQuality: 90, effort: 6 }).toFile(path.join(OUT_DIR, `${name}.webp`));
  }
  console.log(`${CREATURE_NAMES.length} Illustrationen (SVG + WebP) -> ${path.relative(ROOT, OUT_DIR)}/`);

  const sheetIdx = process.argv.indexOf('--sheet');
  if (sheetIdx > 0) {
    const out = process.argv[sheetIdx + 1];
    const CELL = 300;
    const cols = 8;
    const rows = Math.ceil(CREATURE_NAMES.length / cols);
    const tiles = await Promise.all(
      CREATURE_NAMES.map(async (name, i) => {
        const bg = ['#ffe3c4', '#d9efff', '#e3f7d6', '#fff6c8'][Math.floor(i / 8) % 4];
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${CELL}" height="${CELL}"><rect width="100%" height="100%" fill="${bg}"/><g transform="translate(22,10)">${inner(name)}</g><text x="150" y="290" font-family="sans-serif" font-size="16" text-anchor="middle">${name}</text></svg>`;
        return { input: await sharp(Buffer.from(svg)).png().toBuffer(), left: (i % cols) * CELL, top: Math.floor(i / cols) * CELL };
      }),
    );
    await sharp({ create: { width: cols * CELL, height: rows * CELL, channels: 3, background: '#ffffff' } })
      .composite(tiles)
      .png()
      .toFile(out);
    console.log('Übersicht ->', out);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) await main();
